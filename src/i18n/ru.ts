// Source of truth for dictionary keys: uk.ts and en.ts must match this shape.
// Slavic plural: 1 / 2–4 / 5+ (11–14 are "many").
export const slavic = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
};

